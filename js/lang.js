let language = "pl";
try {
  if (localStorage.getItem("selectedLang") === "ua") language = "ua";
} catch {}
const t = (key) => copy[key]?.[language === "ua" ? 1 : 0] || key;
function translate() {
  document.documentElement.lang = language === "ua" ? "uk" : "pl";
  document
    .querySelectorAll("[data-t]")
    .forEach((el) => (el.textContent = t(el.dataset.t)));
  document
    .querySelectorAll("[data-ph]")
    .forEach((el) => (el.placeholder = t(el.dataset.ph)));
  document
    .querySelectorAll("[data-language]")
    .forEach((el) =>
      el.setAttribute("aria-pressed", String(el.dataset.language === language)),
    );
}
function setLanguage(value) {
  if (!["pl", "ua"].includes(value)) return;
  language = value;
  try {
    localStorage.setItem("selectedLang", value);
  } catch {}
  translate();
  document.dispatchEvent(new Event("languagechange"));
}
